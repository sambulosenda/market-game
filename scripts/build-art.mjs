#!/usr/bin/env node
/**
 * Turns the 1024px art originals into the sizes the game draws at.
 *
 *   node scripts/build-art.mjs [path/to/originals]   (default: ./art-src)
 *
 * The originals are not in git and never ship in the app: only the resized
 * files under assets/art are bundled. Each image is cleaned (faint leftover
 * alpha removed), trimmed to its artwork, scaled to its size in points and
 * written at @2x and @3x. The script also writes src/art/manifest.ts, which
 * lists every image with its size in points.
 *
 * Sizes are in points. Every image in a group is scaled by the same factor,
 * so a level 3 shop stays bigger than a level 1 stall.
 */
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.resolve(process.argv[2] ?? path.join(root, 'art-src'));
const outDir = path.join(root, 'assets', 'art');
const manifestPath = path.join(root, 'src', 'art', 'manifest.ts');
const DENSITIES = [2, 3];
/** Alpha at or below this is leftover haze from background removal, not artwork. */
const ALPHA_FLOOR = 12;

/**
 * mode "canvas": the 1024px canvas maps to `points` wide, then the image is trimmed.
 *                Keeps relative sizes between images in the group.
 * mode "fit":    the trimmed artwork is fitted inside a `points` square.
 * mode "band":   a full-width strip; trimmed top and bottom only, scaled to `points` high.
 */
const GROUPS = [
  { dir: 'shops', mode: 'canvas', points: 264 },
  { dir: 'landmarks', mode: 'canvas', points: 264 },
  { dir: 'signs', mode: 'canvas', points: 64 },
  { dir: 'customers', mode: 'canvas', points: 72 },
  { dir: 'goods', mode: 'fit', points: 48 },
  { dir: 'ui', mode: 'fit', points: 48, overrides: { ui_ready_bubble: 72, ui_pantry: 44, ui_panel: 160, ui_order_card: 160, ui_button_primary: 160, ui_button_secondary: 160 } },
  { dir: 'backgrounds', mode: 'band', points: 0, overrides: { bg_sky: 300, bg_rooftops: 120, bg_street: 106 } },
];

async function loadClean(file) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width, height } = info;
  let x0 = width, y0 = height, x1 = -1, y1 = -1;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4 + 3;
      if (data[i] <= ALPHA_FLOOR) {
        data[i] = 0;
      } else {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
    }
  }
  if (x1 < 0) throw new Error(`${file} is fully transparent`);
  return { data, width, height, box: { left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 } };
}

async function build() {
  if (!existsSync(srcDir)) {
    console.error(`No originals at ${srcDir}. Unzip the art archive there, or pass its path.`);
    process.exit(1);
  }
  rmSync(outDir, { recursive: true, force: true });
  const manifest = {};
  let bytes = 0;

  for (const group of GROUPS) {
    const dir = path.join(srcDir, group.dir);
    if (!existsSync(dir)) throw new Error(`Missing folder ${dir}`);
    mkdirSync(path.join(outDir, group.dir), { recursive: true });
    manifest[group.dir] = {};
    for (const file of readdirSync(dir).filter((f) => f.endsWith('.png')).sort()) {
      const name = path.basename(file, '.png');
      const points = group.overrides?.[name] ?? group.points;
      const img = await loadClean(path.join(dir, file));
      let box = img.box;
      let scale; // points per source pixel
      if (group.mode === 'canvas') scale = points / img.width;
      else if (group.mode === 'fit') scale = points / Math.max(box.width, box.height);
      else {
        box = { left: 0, top: box.top, width: img.width, height: box.height };
        scale = points / box.height;
      }
      const w = Math.max(1, Math.round(box.width * scale));
      const h = Math.max(1, Math.round(box.height * scale));
      for (const d of DENSITIES) {
        const out = path.join(outDir, group.dir, `${name}@${d}x.png`);
        const info = await sharp(img.data, { raw: { width: img.width, height: img.height, channels: 4 } })
          .extract(box)
          .resize(w * d, h * d, { kernel: 'lanczos3', fit: 'fill' })
          .png({ palette: true, quality: 90, effort: 10, compressionLevel: 9 })
          .toFile(out);
        bytes += info.size;
      }
      manifest[group.dir][name] = { w, h };
    }
  }

  const lines = [
    '// Generated by scripts/build-art.mjs. Do not edit by hand.',
    '// Sizes are in points. Each image ships at @2x and @3x.',
    '',
    'export type Art = { source: number; w: number; h: number };',
    '',
  ];
  for (const [dir, items] of Object.entries(manifest)) {
    lines.push(`export const ${dir} = {`);
    for (const [name, { w, h }] of Object.entries(items)) {
      lines.push(`  ${name}: { source: require('../../assets/art/${dir}/${name}.png'), w: ${w}, h: ${h} },`);
    }
    lines.push('} satisfies Record<string, Art>;', '');
  }
  mkdirSync(path.dirname(manifestPath), { recursive: true });
  writeFileSync(manifestPath, lines.join('\n'));
  await buildStoreImages();
  const count = Object.values(manifest).reduce((n, g) => n + Object.keys(g).length, 0);
  console.log(`Built ${count} images at ${DENSITIES.map((d) => `@${d}x`).join(' and ')}: ${(bytes / 1024 / 1024).toFixed(1)} MB in assets/art`);
}

/**
 * App icon and splash, which the build tools read from assets/images. The
 * stores require a 1024px icon; it is build input, not part of the JS bundle.
 */
async function buildStoreImages() {
  const icon = path.join(srcDir, 'store', 'app_icon.png');
  const images = path.join(root, 'assets', 'images');
  mkdirSync(images, { recursive: true });
  await sharp(icon).removeAlpha().png({ compressionLevel: 9 }).toFile(path.join(images, 'icon.png'));
  // Android crops adaptive icons to a shape, so the artwork sits in the middle two thirds.
  const inset = await sharp(icon).resize(676, 676).png().toBuffer();
  await sharp({ create: { width: 1024, height: 1024, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
    .composite([{ input: inset, gravity: 'centre' }])
    .png({ compressionLevel: 9 })
    .toFile(path.join(images, 'android-icon-foreground.png'));
  // Splash: the icon with rounded corners, centred on a plain colour.
  const size = 480;
  const mask = Buffer.from(`<svg width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${size * 0.22}"/></svg>`);
  await sharp(icon)
    .resize(size, size)
    .ensureAlpha()
    .composite([{ input: mask, blend: 'dest-in' }])
    .png({ compressionLevel: 9 })
    .toFile(path.join(images, 'splash-icon.png'));
}

build().catch((e) => {
  console.error(e);
  process.exit(1);
});
